/* Data types 

data types for identify the data which type 

1. primitive data types - immutable - unchanged 


2.Non primitive data types - mutable - changes 

*/

//Number - int 
var phoneNumber= 89896986986
console.log(phoneNumber);
console.log(typeof phoneNumber);

//String - single or double quote 
var name="Sasi"
console.log(name);
console.log(typeof name);

var email ="Sasi@mailcom"
console.log(email);

//boolean - return true or false 
var courseisuseful= true
console.log(typeof courseisuseful);
console.log(courseisuseful);

//undefined 
var book
console.log(book);
console.log(typeof book);

